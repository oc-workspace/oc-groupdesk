## Formatting Rules

- 使用中文和中文冒号 `：`。
- 所有可识别的群成员姓名在输出中都必须加单个 `@` 前缀，包括“主要参与者”、活跃发言者榜单，以及“讨论过程”“其他话题”等正文中的人物提及。例如写成 `@小红 提供了一个新话题`，不要写成 `小红提供了一个新话题`。
- 人名已经以 `@` 开头时不得重复添加；使用完整显示名，不改写昵称。不要给群名、产品名、公司名、职位、代词或“有人”“群友”“大家”等泛称添加 `@`。
- 正文中 `@人名` 后留一个空格再接描述，以清楚区分姓名与叙述；连续列举多人时写成 `@小红、@小明`。
- 不使用 Markdown 表格。
- 不增加规定外的顶级章节。
- 语气清晰、具体、有依据，分清原话和点评；对学习成长、创业经营、技术资讯、情感心理的参考价值给予同等关注，允许适度轻松与有温度的表达。
- 不编造金句、笑话、名句作者或出处，不把猜测写成事实，不另加人物排名。
- “今日胡说八道金句”只标记明显的玩笑、夸张、调侃和接梗；不将认真观点、争议资讯或真实情绪当成胡说八道。
- “今日聊天角色”必须有本时段的具体依据，只描述当天表现，不推断年龄、职业、身份、爱好、稳定性格或现实人物关系。
- “今日互动关系”必须来自可确认的回复、引用、点名或连续往返，不按消息相邻关系猜测，不分析现实亲疏或暧昧。
- 不点名当天未发言者，不列潜水名单，不用发言少或工作忙作为调侃素材。
- 不把群友经验改写为普遍事实；争议或未验证信息明确标注。
- 不输出身份证号、手机号、密钥、验证码、家庭住址等高敏感信息。

## Heat Rating

热度表示实际互动，不代替参考价值判断；低热度但重要的信息仍可进入重点。

- `🔥`：单次短交流。
- `🔥🔥`：数条消息形成小范围讨论。
- `🔥🔥🔥`：多位成员持续讨论。
- `🔥🔥🔥🔥`：多轮交流，有明显观点碰撞、实践细节或经验补充。
- `🔥🔥🔥🔥🔥`：该时段主导话题，互动、观点或经验非常丰富。

